/* True if ch falls inside any range of the sorted table (bisection search). */
static int lt__in_table(lt_uchar ch, const struct lt__interval *table,
                        size_t len) {
  size_t lo = 0, hi = len;
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (ch < table[mid].first)
      hi = mid;
    else if (ch > table[mid].last)
      lo = mid + 1;
    else
      return 1;
  }
  return 0;
}

/* True if ch is a wide (2-column) East-Asian or emoji codepoint. Range tests
 * after Kuhn, with the common emoji blocks added. */
static int lt__is_wide(lt_uchar ch) {
  return (ch >= 0x1100 &&
          (ch <= 0x115F || /* Hangul Jamo init. consonants */
           ch == 0x2329 || ch == 0x232A ||
           (ch >= 0x2E80 && ch <= 0xA4CF && ch != 0x303F) || /* CJK..Yi */
           (ch >= 0xAC00 && ch <= 0xD7A3) ||   /* Hangul Syllables */
           (ch >= 0xF900 && ch <= 0xFAFF) ||   /* CJK Compat Ideographs */
           (ch >= 0xFE10 && ch <= 0xFE19) ||   /* Vertical forms */
           (ch >= 0xFE30 && ch <= 0xFE6F) ||   /* CJK Compat Forms */
           (ch >= 0xFF00 && ch <= 0xFF60) ||   /* Fullwidth Forms */
           (ch >= 0xFFE0 && ch <= 0xFFE6) ||   /* Fullwidth signs */
           (ch >= 0x1F300 && ch <= 0x1F64F) || /* Misc symbols + emoticons */
           (ch >= 0x1F900 && ch <= 0x1F9FF) || /* Supplemental symbols */
           (ch >= 0x20000 && ch <= 0x3FFFD))); /* CJK Ext B..plane 3 */
}

int lt__wcwidth(lt_uchar ch) {
  if (ch == 0)
    return 0;

  /* C0/C1 control characters (and DEL) are non-printable. */
  if (ch < 0x20 || (ch >= 0x7F && ch < 0xA0))
    return -1;

  if (lt__in_table(ch, lt__zero_width,
                   sizeof(lt__zero_width) / sizeof(lt__zero_width[0])))
    return 0;

  return lt__is_wide(ch) ? 2 : 1;
}

int lt_wcwidth(uint32_t ch) { return lt__wcwidth((lt_uchar)ch); }

int lt_iswprint(uint32_t ch) { return lt__wcwidth((lt_uchar)ch) >= 0 ? 1 : 0; }

int lt_attr_width(void) { return (int)sizeof(lt_attr); }
